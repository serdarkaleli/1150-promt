export function getBilingualTitle(originalTitle: string): string {
  if (!originalTitle) return '';
  const trimmed = originalTitle.trim();
  
  // 1. Direct dictionary match
  if (TITLE_TR_MAP[trimmed]) {
    return `${trimmed} (${TITLE_TR_MAP[trimmed]})`;
  }

  // 2. Check if already has bilingual format: "Original (Turkish)"
  for (const [eng, tr] of Object.entries(TITLE_TR_MAP)) {
    if (trimmed === `${eng} (${tr})` || trimmed.endsWith(`(${tr})`)) {
      return trimmed;
    }
  }

  // 3. Strip leading emojis/phase badges
  const cleanKey = trimmed.replace(/^[🎯📋🏗️💻⚙️🔗✅🚀🔄📚🏁🔨🔧🐛📝⚡🤖]+\s*/, '').trim();
  if (TITLE_TR_MAP[cleanKey]) {
    return `${trimmed} (${TITLE_TR_MAP[cleanKey]})`;
  }

  return trimmed;
}
